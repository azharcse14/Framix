#!/usr/bin/env python3
"""Task tracker for the Framix plan.

Single source of truth: tasks/tasks.json. Statuses: todo, in_progress, done.
Every change re-renders docs/plan.md checkboxes and docs/TASKS.md, so never
edit those (or tasks.json) by hand.

Examples:
  python3 scripts/task.py next
  python3 scripts/task.py start P1-012
  python3 scripts/task.py note P1-012 "blocked: waiting for device test"
  python3 scripts/task.py done P1-012 --commit abc1234
  python3 scripts/task.py add P1 "Fix seek drift on VFR clips" --tags Rust
  python3 scripts/task.py list --status in_progress
  python3 scripts/task.py check
"""
import argparse
import datetime
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks" / "tasks.json"
PLAN = ROOT / "docs" / "plan.md"
BOARD = ROOT / "docs" / "TASKS.md"
STATUSES = ("todo", "in_progress", "done")
TAGS = ("Dart", "Rust", "C++", "Native", "ML", "Backend", "—")
ID_RE = re.compile(r"^- \[( |x)\] `([A-Z0-9]+-\d{3})` ")


class TaskError(Exception):
    pass


def today():
    return datetime.date.today().isoformat()


def git(*args):
    try:
        out = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True)
        return out.stdout.strip() or None
    except (OSError, subprocess.CalledProcessError):
        return None


def load():
    return json.loads(TASKS.read_text(encoding="utf-8"))


def save(data):
    TASKS.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def find(data, tid):
    for t in data["tasks"]:
        if t["id"] == tid:
            return t
    raise TaskError(f"unknown task id: {tid}")


def guard_owner(t, as_human):
    if t["owner"] == "human" and not as_human:
        raise TaskError(f"{t['id']} is owned by a human; only a human changes its status (--as-human)")


def add_note(t, text):
    t["notes"].append({"date": today(), "text": text})


def section_order(data):
    """Order used by `next`: tasks.json "work_order" if present, else doc order."""
    return {p: i for i, p in enumerate(data.get("work_order") or data["sections"])}


def next_tasks(data, section=None):
    order = section_order(data)
    index = {t["id"]: i for i, t in enumerate(data["tasks"])}
    cands = [
        t for t in data["tasks"]
        if t["status"] == "todo" and t["owner"] == "claude" and not t["deferred"]
        and (section is None or t["section"] == section)
    ]
    cands.sort(key=lambda t: (order.get(t["section"], 999), 1 if t.get("subphase") == "1b" else 0, index[t["id"]]))
    return cands


# ---------- rendering

def render_plan(data):
    lines = PLAN.read_text(encoding="utf-8").split("\n")
    by_id = {t["id"]: t for t in data["tasks"]}
    present = set()
    for i, ln in enumerate(lines):
        m = ID_RE.match(ln)
        if m and m.group(2) in by_id:
            present.add(m.group(2))
            box = "x" if by_id[m.group(2)]["status"] == "done" else " "
            lines[i] = f"- [{box}] " + ln[6:]
    for t in data["tasks"]:
        if t["id"] in present:
            continue
        box = "x" if t["status"] == "done" else " "
        tags = "".join(f" \\[{g}\\]" for g in t["tags"])
        new = f"- [{box}] `{t['id']}` {t['title']}{tags}"
        heading = "## " + data["sections"].get(t["section"], "")
        pos = insert_position(lines, heading)
        if pos is None:
            if "## Added tasks" not in lines:
                lines += ["", "## Added tasks", ""]
            lines.append(new)
        else:
            lines.insert(pos, new)
    PLAN.write_text("\n".join(lines), encoding="utf-8")


def insert_position(lines, heading):
    """Index right after the last task line of the section with this heading."""
    try:
        start = lines.index(heading)
    except ValueError:
        return None
    last = None
    fence = False
    for i in range(start + 1, len(lines)):
        if lines[i].startswith("```"):
            fence = not fence
        if not fence and lines[i].startswith("## "):
            break
        if not fence and ID_RE.match(lines[i]):
            last = i
    return None if last is None else last + 1


def cell(s):
    return s.replace("|", "\\|")


def render_board(data):
    order = list(data["sections"])
    rows = []
    totals = dict.fromkeys(STATUSES, 0)
    for p in order:
        ts = [t for t in data["tasks"] if t["section"] == p]
        c = {s: sum(t["status"] == s for t in ts) for s in STATUSES}
        for s in STATUSES:
            totals[s] += c[s]
        rows.append(f"| {p} | {cell(data['sections'][p])} | {c['todo']} | {c['in_progress']} | {c['done']} | {len(ts)} |")
    out = [
        "# Task board",
        "",
        "_Generated by `scripts/task.py`. Do not edit by hand._",
        "",
        f"**Total:** {sum(totals.values())} tasks · todo {totals['todo']} · in progress {totals['in_progress']} · done {totals['done']}",
        "",
        "| Prefix | Section | Todo | In progress | Done | Total |",
        "| --- | --- | --- | --- | --- | --- |",
        *rows,
        "",
        "## In progress",
        "",
    ]
    prog = [t for t in data["tasks"] if t["status"] == "in_progress"]
    if prog:
        out += ["| ID | Task | Owner | Started | Branch | Last note |", "| --- | --- | --- | --- | --- | --- |"]
        for t in prog:
            note = t["notes"][-1]["text"] if t["notes"] else ""
            out.append(f"| {t['id']} | {cell(t['title'][:90])} | {t['owner']} | {t['started'] or ''} | {t['branch'] or ''} | {cell(note[:80])} |")
    else:
        out.append("Nothing in progress.")
    out += ["", "## Recently done", ""]
    done = sorted((t for t in data["tasks"] if t["status"] == "done"), key=lambda t: t["done"] or "", reverse=True)[:20]
    if done:
        out += ["| ID | Task | Done | Commit |", "| --- | --- | --- | --- |"]
        for t in done:
            out.append(f"| {t['id']} | {cell(t['title'][:90])} | {t['done'] or ''} | {t['commit'] or ''} |")
    else:
        out.append("Nothing done yet.")
    out += ["", "## Next up (owner claude, not deferred)", ""]
    for t in next_tasks(data)[:10]:
        out.append(f"- {t['id']}: {t['title'][:100]}")
    added = [t for t in data["tasks"] if t.get("source") == "added"]
    if added:
        out += ["", "## Added during work", ""]
        for t in added:
            out.append(f"- {t['id']} ({t['status']}): {t['title'][:100]}")
    BOARD.write_text("\n".join(out) + "\n", encoding="utf-8")


def commit_changes(data):
    save(data)
    render_plan(data)
    render_board(data)


# ---------- validation

def validate(data):
    errors, warnings = [], []
    ids = [t["id"] for t in data["tasks"]]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        errors.append(f"duplicate ids: {sorted(dupes)}")
    plan_ids = []
    fence = False
    for ln in PLAN.read_text(encoding="utf-8").split("\n"):
        if ln.startswith("```"):
            fence = not fence
        m = ID_RE.match(ln)
        if m and not fence:
            plan_ids.append(m.group(2))
    missing_in_json = set(plan_ids) - set(ids)
    missing_in_plan = set(ids) - set(plan_ids)
    if missing_in_json:
        errors.append(f"in plan.md but not tasks.json: {sorted(missing_in_json)}")
    if missing_in_plan:
        errors.append(f"in tasks.json but not plan.md (run: task.py render): {sorted(missing_in_plan)}")
    by_branch = {}
    for t in data["tasks"]:
        if t["status"] not in STATUSES:
            errors.append(f"{t['id']}: bad status {t['status']!r}")
        if t["status"] == "in_progress" and not t["started"]:
            errors.append(f"{t['id']}: in_progress without start date")
        if t["status"] == "done" and not t["done"]:
            errors.append(f"{t['id']}: done without done date")
        if t["status"] == "in_progress" and t["owner"] == "claude":
            by_branch.setdefault(t["branch"], []).append(t["id"])
    for b, ts in by_branch.items():
        if len(ts) > 1:
            warnings.append(f"branch {b}: {len(ts)} claude tasks in progress ({', '.join(ts)}); finish one first")
    return errors, warnings


# ---------- commands

def cmd_list(data, a):
    for t in data["tasks"]:
        if a.status and t["status"] != a.status:
            continue
        if a.section and t["section"] != a.section:
            continue
        if a.owner and t["owner"] != a.owner:
            continue
        if t["deferred"] and not a.include_deferred:
            continue
        print(f"{t['id']:9} {t['status']:11} {t['owner']:6} {t['title'][:100]}")


def cmd_show(data, a):
    print(json.dumps(find(data, a.id), ensure_ascii=False, indent=2))


def cmd_start(data, a):
    t = find(data, a.id)
    guard_owner(t, a.as_human)
    if t["status"] == "done":
        raise TaskError(f"{t['id']} is done; use reopen first")
    t.update(status="in_progress", started=t["started"] or today(), branch=git("rev-parse", "--abbrev-ref", "HEAD"))
    if a.note:
        add_note(t, a.note)
    commit_changes(data)
    print(f"{t['id']} -> in_progress")
    _, warnings = validate(data)
    for w in warnings:
        print("warning:", w, file=sys.stderr)


def cmd_done(data, a):
    t = find(data, a.id)
    guard_owner(t, a.as_human)
    if t["status"] != "in_progress":
        raise TaskError(f"{t['id']} is {t['status']}; start it before marking done")
    t.update(status="done", done=today(), commit=a.commit or git("rev-parse", "--short", "HEAD"))
    if a.note:
        add_note(t, a.note)
    commit_changes(data)
    print(f"{t['id']} -> done")


def cmd_reopen(data, a):
    t = find(data, a.id)
    guard_owner(t, a.as_human)
    t.update(status="todo", done=None, commit=None)
    add_note(t, "reopened: " + a.note)
    commit_changes(data)
    print(f"{t['id']} -> todo")


def cmd_note(data, a):
    t = find(data, a.id)
    add_note(t, a.text)
    commit_changes(data)
    print(f"note added to {t['id']}")


def cmd_add(data, a):
    if a.prefix not in data["sections"]:
        raise TaskError(f"unknown section prefix {a.prefix}; known: {', '.join(data['sections'])}")
    tags = [g.strip() for g in a.tags.split(",")] if a.tags else []
    bad = [g for g in tags if g not in TAGS]
    if bad:
        raise TaskError(f"unknown tags {bad}; allowed: {', '.join(TAGS)}")
    nums = [int(t["id"].split("-")[1]) for t in data["tasks"] if t["section"] == a.prefix]
    tid = f"{a.prefix}-{(max(nums) if nums else 0) + 1:03d}"
    owner = "human" if not tags or set(tags) <= {"—"} else "claude"
    data["tasks"].append({
        "id": tid, "section": a.prefix, "group": a.group, "title": a.title, "tags": tags,
        "owner": owner, "deferred": bool(tags) and set(tags) <= {"Backend", "—"} and "Backend" in tags,
        "subphase": None, "status": "todo", "started": None, "done": None, "commit": None,
        "branch": None, "notes": [], "source": "added",
    })
    commit_changes(data)
    print(f"added {tid} ({owner})")


def cmd_next(data, a):
    ts = next_tasks(data, a.section)
    if not ts:
        print("no todo task for claude")
    for t in ts[: a.n]:
        print(f"{t['id']:9} {t['title'][:100]}")


def cmd_render(data, a):
    commit_changes(data)
    print("rendered docs/plan.md and docs/TASKS.md")


def cmd_check(data, a):
    errors, warnings = validate(data)
    for w in warnings:
        print("warning:", w, file=sys.stderr)
    for e in errors:
        print("error:", e, file=sys.stderr)
    if errors:
        sys.exit(1)
    print(f"tasks ok ({len(data['tasks'])} tasks)")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("list"); s.add_argument("--status", choices=STATUSES); s.add_argument("--section")
    s.add_argument("--owner", choices=("claude", "human")); s.add_argument("--include-deferred", action="store_true")
    s = sub.add_parser("show"); s.add_argument("id")
    for name in ("start", "done"):
        s = sub.add_parser(name); s.add_argument("id"); s.add_argument("--note")
        s.add_argument("--as-human", action="store_true")
        if name == "done":
            s.add_argument("--commit")
    s = sub.add_parser("reopen"); s.add_argument("id"); s.add_argument("note"); s.add_argument("--as-human", action="store_true")
    s = sub.add_parser("note"); s.add_argument("id"); s.add_argument("text")
    s = sub.add_parser("add"); s.add_argument("prefix"); s.add_argument("title")
    s.add_argument("--tags", help="comma separated: " + ",".join(TAGS)); s.add_argument("--group")
    s = sub.add_parser("next"); s.add_argument("--section"); s.add_argument("-n", type=int, default=5)
    sub.add_parser("render")
    sub.add_parser("check")
    a = p.parse_args(argv)
    data = load()
    try:
        globals()["cmd_" + a.cmd](data, a)
    except TaskError as e:
        print("error:", e, file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
